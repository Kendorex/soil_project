//! Irrigation methods, modes, and schedule records.

/// Externally supplied irrigation for one consecutive simulation day.
#[derive(Clone, Debug)]
#[cfg_attr(feature = "serde", derive(serde::Serialize, serde::Deserialize))]
#[cfg_attr(feature = "serde", serde(rename_all = "camelCase"))]
pub struct DailyIrrigation {
    /// Applied irrigation depth, in millimetres.
    pub depth: f64,
    /// Irrigation-water electrical conductivity, in dS/m.
    pub conductivity: f64,
}

/// Field application method.
#[derive(Clone, Debug)]
#[cfg_attr(feature = "serde", derive(serde::Serialize, serde::Deserialize))]
#[cfg_attr(feature = "serde", serde(rename_all = "snake_case"))]
pub enum IrrigationMethod {
    /// Sprinkler irrigation.
    Sprinkler,
    /// Basin irrigation.
    Basin,
    /// Border irrigation.
    Border,
    /// Furrow irrigation.
    Furrow,
    /// Drip irrigation.
    Drip,
}

/// Trigger used when irrigation is generated by the model.
#[derive(Clone, Debug)]
#[cfg_attr(feature = "serde", derive(serde::Serialize, serde::Deserialize))]
#[cfg_attr(feature = "serde", serde(rename_all = "snake_case"))]
pub enum IrrigationTimeCriterion {
    /// Fixed interval between applications.
    FixedInterval,
    /// Allowable root-zone depletion, in millimetres.
    RootZoneDepletion,
    /// Allowable depletion of readily available water, in percent.
    ReadilyAvailableWaterDepletion,
    /// Target water level retained between bunds.
    WaterBetweenBunds,
}

/// Depth rule used when irrigation is generated by the model.
#[derive(Clone, Debug, PartialEq, Eq)]
#[cfg_attr(feature = "serde", derive(serde::Serialize, serde::Deserialize))]
#[cfg_attr(feature = "serde", serde(rename_all = "snake_case"))]
pub enum IrrigationDepthCriterion {
    /// Refill the root zone to field capacity.
    ToFieldCapacity,
    /// Apply a fixed water depth.
    FixedDepth,
}

/// Irrigation scheduling mode and its mode-specific header values.
#[derive(Clone, Debug)]
#[cfg_attr(feature = "serde", derive(serde::Serialize, serde::Deserialize))]
#[cfg_attr(
    feature = "serde",
    serde(
        tag = "type",
        rename_all = "snake_case",
        rename_all_fields = "camelCase"
    )
)]
pub enum IrrigationMode {
    /// Rainfed cropping.
    Rainfed,
    /// Explicit daily schedule.
    Manual {
        /// Absolute day number corresponding to schedule day one, or `None` for crop day one.
        first_day_number: Option<i32>,
    },
    /// Rules generated over one or more crop-cycle windows.
    Generated {
        /// Trigger rule.
        time_criterion: IrrigationTimeCriterion,
        /// Applied-depth rule.
        depth_criterion: IrrigationDepthCriterion,
        /// Days before crop-cycle end during which irrigation is disabled, when configured.
        end_exclusion: Option<i32>,
    },
    /// Net irrigation requirement calculation.
    NetRequirement {
        /// Allowed readily available water depletion, in percent.
        readily_available_water_depletion: i32,
    },
}

impl IrrigationMode {
    /// Whether generated irrigation is permitted on an absolute simulation day.
    ///
    /// The 7.3 cutoff begins at `crop_last_day - end_exclusion + 1`.
    /// Both arguments are absolute AquaCrop day numbers, measured in calendar
    /// days from 1 January 1901.
    #[must_use]
    #[expect(
        clippy::int_plus_one,
        reason = "the expression preserves the documented AquaCrop 7.3 cutoff boundary"
    )]
    pub fn generated_irrigation_allowed(&self, day: i32, crop_last_day: i32) -> bool {
        !matches!(
            self,
            Self::Generated {
                end_exclusion,
                ..
            } if end_exclusion.is_some_and(|end_exclusion| {
                day >= crop_last_day - end_exclusion + 1
            })
        )
    }
}

/// One manual or generated irrigation record.
#[derive(Clone, Debug)]
#[cfg_attr(feature = "serde", derive(serde::Serialize, serde::Deserialize))]
#[cfg_attr(
    feature = "serde",
    serde(
        tag = "type",
        rename_all = "snake_case",
        rename_all_fields = "camelCase"
    )
)]
pub enum IrrigationRecord {
    /// Explicit irrigation on a crop-schedule day.
    Manual {
        /// Day relative to the configured schedule origin.
        day: i32,
        /// Applied irrigation depth, in millimetres.
        depth: i32,
        /// Irrigation-water electrical conductivity, in dS/m, when stored per record.
        electrical_conductivity: Option<f64>,
    },
    /// Generated-irrigation rule beginning on a crop-cycle day.
    Generated {
        /// First crop-cycle day governed by the rule.
        from_day: i32,
        /// Time-trigger parameter in the units selected by the header criterion.
        time_parameter: i32,
        /// Mode-specific depth adjustment in millimetres, when present.
        depth_parameter: Option<i32>,
        /// Irrigation-water electrical conductivity, in dS/m, when stored per record.
        electrical_conductivity: Option<f64>,
    },
}

/// Complete irrigation configuration and schedule.
#[derive(Clone, Debug)]
#[cfg_attr(feature = "serde", derive(serde::Serialize, serde::Deserialize))]
#[cfg_attr(feature = "serde", serde(rename_all = "camelCase"))]
pub struct IrrigationSchedule {
    /// Field application method.
    pub method: IrrigationMethod,
    /// Soil surface wetted during the crop season, in percent.
    pub wetted_surface: i8,
    /// Scheduling mode and its mode-specific parameters.
    pub mode: IrrigationMode,
    /// Manual applications or generated-rule windows.
    pub records: Vec<IrrigationRecord>,
}
