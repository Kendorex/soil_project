def main():
    source = read_json(PROJECT / 'configs/rotation_fixed.apsimx')
    nodes = list(walk(source))
    zones = [(path, n) for path, n in nodes if n.get('$type') == 'Models.Core.Zone, Models' and re.fullmatch(r'Field\d+', n.get('Name', ''))]
    crop_inventory = []
    for directory, scenario in [(PROJECT / 'DATA/crops/transferred', 'catalog'),
                                 (PROJECT / 'generated', 'baseline'),
                                 (PROJECT / 'calibration_vniimz/generated', 'calibrated')]:
        for path in sorted(directory.rglob('*.CRO')):
            lines = path.read_text(encoding='utf-8-sig').splitlines()
            parameters = []
            for number, (name, unit, meaning) in MEANINGS.items():
                if number > len(lines):
                    continue
                token = lines[number - 1].split()[0]
                try:
                    value = float(token)
                except ValueError:
                    raise ValueError(f'Invalid numeric line {path}:{number}')
                parameters.append(dict(line=number, name=name, unit=unit, meaning=meaning,
                                       value=value, source_comment=lines[number - 1].partition(':')[2].strip()))
            # Old field_XX scenarios are not part of the current fixed rotation.
            if scenario != 'catalog' and not path.relative_to(directory).parts[0].startswith('fixed_field_'):
                continue
            crop_inventory.append(dict(scenario=scenario, file=path.relative_to(ROOT).as_posix(),
                                       description=lines[0], parameters=parameters))
    cultivar_rows = []
    snapshots = []
    for zone_path, zone in zones:
        for path, node in walk(zone, zone_path.rsplit('/', 1)[0]):
            kind = node.get('$type', '')
            if kind == 'Models.PMF.Cultivar, Models':
                for command in node.get('Command', []):
                    if command.strip():
                        cultivar_rows.append(dict(field=zone['Name'], cultivar=node['Name'], path=path,
                                                  command=command, meaning=explain_command(command)))
        snapshots.append(dict(field=zone['Name'], path=zone_path,
                              plants=[{k:n.get(k) for k in ['Name', '$type', 'ResourceName', 'Enabled']} for _,n in walk(zone) if n.get('$type')=='Models.PMF.Plant, Models'],
                              soil_nodes=[{k:v for k,v in n.items() if k!='Children'} for _,n in walk(zone) if n.get('$type','').startswith('Models.Soils.')],
                              managers=[{k:n.get(k) for k in ['Name','Enabled','Parameters']} for _,n in walk(zone) if n.get('$type')=='Models.Manager, Models']))
